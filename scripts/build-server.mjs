// Build a release directory for the server (dist/release):
//   api/main.mjs + api/app.cjs (Passenger startup file) · worker/{run,cleanup,stats}.mjs · migrate.mjs
//   migrations/ · web/ (Vite build) · py/mediaworker (pip-installable) · package.json (pg + sodium-native only)
// Everything else is bundled, so the server's node_modules holds two packages instead of ~30,000 files.
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'dist/release');
const EXTERNAL = ['pg', 'pg-native', 'sodium-native'];
const sha = (() => {
  try {
    const s = execFileSync('git', ['rev-parse', '--short=12', 'HEAD'], { cwd: root }).toString().trim();
    const dirty = execFileSync('git', ['status', '--porcelain'], { cwd: root }).toString().trim();
    return dirty ? `${s}-dirty-${Date.now().toString(36)}` : s;
  } catch {
    return `nogit-${Date.now().toString(36)}`;
  }
})();

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const entries = {
  'api/main': 'apps/api/src/server.ts',
  'worker/run': 'apps/worker/src/run.ts',
  'worker/cleanup': 'apps/worker/src/cleanup-cli.ts',
  'worker/stats': 'apps/worker/src/stats-cli.ts',
  migrate: 'scripts/migrate.ts',
};
await build({
  entryPoints: Object.fromEntries(Object.entries(entries).map(([k, v]) => [k, path.join(root, v)])),
  outdir: out,
  outExtension: { '.js': '.mjs' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  sourcemap: true,
  external: EXTERNAL,
  legalComments: 'none',
  // Some CommonJS dependencies call require(); give ESM bundles one.
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  define: { 'process.env.ACM_RELEASE': JSON.stringify(sha) },
  logLevel: 'warning',
});

// Passenger loads a CommonJS startup file; it reads shared/.env, then starts the ESM bundle.
writeFileSync(
  path.join(out, 'api/app.cjs'),
  `// Passenger startup file (generated by scripts/build-server.mjs).
const path = require('node:path');
try { process.loadEnvFile(path.join(__dirname, '../../../shared/.env')); } catch (e) { console.error('shared/.env not loaded:', e.message); }
process.env.WEB_ROOT ??= path.join(__dirname, '../web');
process.env.UV_THREADPOOL_SIZE ??= '4';
import('./main.mjs').catch((e) => { console.error(e); process.exit(1); });
`,
);

cpSync(path.join(root, 'migrations'), path.join(out, 'migrations'), { recursive: true });
cpSync(path.join(root, 'apps/web/dist'), path.join(out, 'web'), { recursive: true });
cpSync(path.join(root, 'py/mediaworker'), path.join(out, 'py/mediaworker'), {
  recursive: true,
  filter: (src) => !/(\.venv|__pycache__|\.pytest_cache|\.egg-info|tests)(\/|$)/.test(src),
});
cpSync(path.join(root, 'luts'), path.join(out, 'luts'), { recursive: true });
cpSync(path.join(root, 'deploy'), path.join(out, 'deploy'), { recursive: true });

const lock = JSON.parse(readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
// The version actually installed for the server code: hoisted at the root, or nested under a workspace.
const version = (name) => {
  const v = lock.packages[`node_modules/${name}`]?.version ?? Object.entries(lock.packages).find(([k]) => k.endsWith(`/node_modules/${name}`))?.[1].version;
  if (!v) throw new Error(`${name} is not in package-lock.json`);
  return v;
};
writeFileSync(
  path.join(out, 'package.json'),
  JSON.stringify({ name: 'acm-media-release', private: true, type: 'module', engines: { node: '>=24' }, dependencies: { pg: version('pg'), 'sodium-native': version('sodium-native') } }, null, 2) + '\n',
);
writeFileSync(path.join(out, 'RELEASE'), `${sha}\n`);
console.log(`built ${path.relative(root, out)} (${sha})`);
